CREATE TABLE IF NOT EXISTS public.billstack_backfill_jobs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  requested_by UUID NOT NULL REFERENCES auth.users(id),
  status TEXT NOT NULL CHECK (status IN ('preparing', 'running', 'completed', 'failed')),
  total_users INTEGER NOT NULL DEFAULT 0,
  error_message TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS billstack_backfill_one_active_job_idx
  ON public.billstack_backfill_jobs ((true))
  WHERE status IN ('preparing', 'running');

CREATE TABLE IF NOT EXISTS public.billstack_backfill_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id UUID NOT NULL REFERENCES public.billstack_backfill_jobs(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'processing', 'completed', 'skipped', 'failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  error_message TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (job_id, user_id)
);

CREATE INDEX IF NOT EXISTS billstack_backfill_items_queue_idx
  ON public.billstack_backfill_items (job_id, status, id);

ALTER TABLE public.billstack_backfill_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.billstack_backfill_items ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.billstack_backfill_jobs FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.billstack_backfill_items FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.billstack_backfill_jobs TO service_role;
GRANT ALL ON public.billstack_backfill_items TO service_role;

CREATE OR REPLACE FUNCTION public.claim_billstack_backfill_items(
  p_job_id UUID,
  p_batch_size INTEGER
)
RETURNS TABLE (item_id BIGINT, user_id UUID)
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public
AS $function$
  WITH candidates AS (
    SELECT item.id
    FROM public.billstack_backfill_items AS item
    WHERE item.job_id = p_job_id
      AND (
        item.status = 'pending'
        OR (
          item.status = 'processing'
          AND item.updated_at < now() - interval '3 minutes'
        )
      )
    ORDER BY item.id
    FOR UPDATE SKIP LOCKED
    LIMIT LEAST(GREATEST(p_batch_size, 1), 5)
  )
  UPDATE public.billstack_backfill_items AS item
  SET status = 'processing',
      attempts = item.attempts + 1,
      updated_at = now()
  FROM candidates
  WHERE item.id = candidates.id
  RETURNING item.id, item.user_id;
$function$;

REVOKE ALL ON FUNCTION public.claim_billstack_backfill_items(UUID, INTEGER)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_billstack_backfill_items(UUID, INTEGER)
  TO service_role;
